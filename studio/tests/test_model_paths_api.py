import json
import tempfile
import unittest
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from aiohttp.test_utils import TestClient, TestServer

from nomas_app.models import ModelLocations
from nomas_app.server import Studio, make_app


class ModelPathsAPITests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="Nomas API ")
        self.root = Path(self.temp.name)
        (self.root / "models.manifest.json").write_text(json.dumps({"models": [
            dict(id="dit", local="models/dit.safetensors", remote="DiT/file.safetensors", size=100)
        ]}), encoding="utf-8")
        self.studio = Studio()
        self.studio.locations = ModelLocations(self.root)
        # Bound host is generated by the test server; production only allows loopback origins.
        self.client = TestClient(TestServer(make_app(self.studio), host="127.0.0.1"))
        await self.client.start_server()

    async def asyncTearDown(self):
        self.studio.task = None
        self.studio.engine.world = None
        await self.client.close()
        self.temp.cleanup()

    async def test_round_trip_and_restart(self):
        response = await self.client.post("/api/model-paths", json={"model_root": str(self.root)})
        self.assertEqual(response.status, 200)
        data = await (await self.client.get("/api/model-paths")).json()
        self.assertEqual(data["settings"]["model_root"], str(self.root))
        self.assertFalse(data["models"][0]["ready"])
        self.assertEqual(ModelLocations(self.root).preferences()["model_root"], str(self.root))

    async def test_missing_file_is_bad_request_not_saved(self):
        response = await self.client.post("/api/model-paths", json={"dit": "missing.safetensors"})
        self.assertEqual(response.status, 400)
        self.assertIn("文件不存在", await response.text())
        self.assertFalse(self.studio.locations.config_file.exists())

    async def test_running_job_and_existing_world_protected(self):
        self.studio.task = object()
        response = await self.client.post("/api/model-paths", json={})
        self.assertEqual(response.status, 409)
        self.studio.task = None
        self.studio.engine.world = object()
        response = await self.client.post("/api/model-paths", json={})
        self.assertEqual(response.status, 409)

    async def test_cross_origin_writes_rejected(self):
        response = await self.client.post("/api/model-paths", json={}, headers={"Origin": "https://example.com"})
        self.assertEqual(response.status, 403)
        self.assertFalse(self.studio.locations.config_file.exists())

    async def test_invalid_payload(self):
        for data in ([], {"dit": 123}):
            response = await self.client.post("/api/model-paths", json=data)
            self.assertEqual(response.status, 400)

    async def test_corrupt_settings_can_be_restored_from_ui(self):
        config = self.studio.locations.config_file
        config.parent.mkdir()
        config.write_text("broken JSON", encoding="utf-8")
        response = await self.client.get("/api/status")
        self.assertEqual(response.status, 200)
        self.assertFalse((await response.json())["models"][0]["ready"])
        self.assertEqual((await self.client.get("/api/model-paths")).status, 400)
        self.assertEqual((await self.client.post("/api/model-paths", json={})).status, 200)
        self.assertEqual((await self.client.get("/api/model-paths")).status, 200)


if __name__ == "__main__":
    unittest.main()
